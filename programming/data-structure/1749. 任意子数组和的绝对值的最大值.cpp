class Solution {
public:
    // 前缀最值增量维护模板 · 档位 A（一个变量）
    //
    // 子数组 [l..r] 的和 = pref[r+1] - pref[l]，记 i = l、j = r+1（i < j），
    // 其绝对值最大即求：
    //     max over j of ( pref[j] - min_{i<j} pref[i],  max_{i<j} pref[i] - pref[j] )
    // 前者是最大正向差（最大子数组和），后者是最大反向差（最小子数组和取负）。
    //
    // 扫描每个前缀和 s：先用「历史最小/最大前缀」更新答案，再把 s 并入历史。
    // f = 前缀和 mn/mx，g = 前缀和 s，op = '-'，约束 i < j（严格）。
    int maxAbsoluteSum(vector<int>& nums) {
        int s = 0;          // 当前前缀和 pref[j]
        int mn = 0, mx = 0; // 历史前缀和的最小/最大值（含空前缀 pref[0] = 0）
        int ans = 0;
        for (int x : nums) {
            s += x;
            // 先算：与 i<j 的历史前缀比较，正向差 s-mn 与反向差 mx-s 取大
            ans = max(ans, max(s - mn, mx - s));
            // 再更新：把当前前缀并入历史（约束严格 i<j，故更新放在算之后）
            mn = min(mn, s);
            mx = max(mx, s);
        }
        return ans;
    }
};
